"""Cosmetic catalogue, upload, download and (development-only) deletion."""

from __future__ import annotations

import hashlib
import logging
import re
import sqlite3
import uuid
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, File, Form, Query, Request, UploadFile
from fastapi.responses import FileResponse

import auth
import config
import models
from database import get_connection
from errors import ApiError
from schemas import CosmeticListResponse, CosmeticResponse, DeleteResponse, ErrorResponse
from services.cosmetic_storage import (
    MAX_NAME_LENGTH,
    CosmeticStorage,
    ValidationError,
    clean_filename,
    clean_text,
    has_allowed_extension,
    validate_bbmodel,
)

logger = logging.getLogger("orbit.cosmetics")
router = APIRouter(prefix=f"{config.API_PREFIX}/cosmetics", tags=["cosmetics"])

COSMETIC_ID = re.compile(r"^[0-9a-f]{32}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")
NOT_FOUND = {404: {"model": ErrorResponse, "description": "No cosmetic with this ID"}}


def _storage(request: Request) -> CosmeticStorage:
    return request.app.state.storage


def require_development(request: Request) -> None:
    """Destructive actions over HTTP exist for local testing only. In production use manage.py on the server."""
    settings = request.app.state.settings
    if not settings.dev_mode:
        raise ApiError(403, "development_only", "This endpoint is only available in development mode; use manage.py on the server.")
    if not auth.is_local_request(request):
        logger.warning("Refused development-only request from %s", auth.client_ip(request))
        raise ApiError(403, "development_only", "This endpoint only accepts requests from this computer.")


def _find(connection: sqlite3.Connection, cosmetic_id: str) -> models.Cosmetic:
    # IDs are generated by the server; anything else cannot exist, so it is not even looked up.
    cosmetic = models.get(connection, cosmetic_id) if COSMETIC_ID.match(cosmetic_id) else None
    if cosmetic is None:
        raise ApiError(404, "not_found", "No cosmetic with this ID exists.")
    return cosmetic


@router.get("", response_model=CosmeticListResponse, summary="List registered cosmetics")
def list_cosmetics(
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    connection: sqlite3.Connection = Depends(get_connection),
) -> CosmeticListResponse:
    items = [CosmeticResponse.from_model(c, config.API_PREFIX) for c in models.list_all(connection, limit, offset)]
    return CosmeticListResponse(items=items, total=models.count(connection), limit=limit, offset=offset)


@router.post(
    "/upload",
    response_model=CosmeticResponse,
    status_code=201,
    summary="Upload a .bbmodel file (signed-in players in production; this computer in development)",
    responses={
        400: {"model": ErrorResponse, "description": "Empty file, invalid JSON or not a Blockbench project"},
        401: {"model": ErrorResponse, "description": "Production: no valid player session"},
        403: {"model": ErrorResponse, "description": "Read-only server, blocked player, or (development) not from this computer"},
        429: {"model": ErrorResponse, "description": "Daily upload quota reached"},
        507: {"model": ErrorResponse, "description": "The server's storage limit is reached"},
        409: {"model": ErrorResponse, "description": "The same file was already uploaded"},
        413: {"model": ErrorResponse, "description": "File larger than the upload limit"},
        415: {"model": ErrorResponse, "description": "Not a .bbmodel or .json file"},
    },
)
async def upload_cosmetic(
    request: Request,
    file: UploadFile = File(..., description="A Blockbench project (.bbmodel or .json)"),
    display_name: str | None = Form(None, description="Name shown in the catalogue; defaults to the model's name"),
    connection: sqlite3.Connection = Depends(get_connection),
) -> CosmeticResponse:
    writer = auth.require_writer(request, connection)
    settings = request.app.state.settings
    original_filename = clean_filename(file.filename)
    if not has_allowed_extension(original_filename):
        raise ApiError(415, "unsupported_file_type", "Only .bbmodel and .json files are accepted.")

    data = await file.read(settings.max_upload_bytes + 1)
    if len(data) > settings.max_upload_bytes:
        raise ApiError(413, "too_large", f"The file is larger than the {settings.max_upload_bytes // 1024} KiB upload limit.")

    try:
        validated = validate_bbmodel(data)
    except ValidationError as error:
        logger.info("Rejected upload %r: %s", original_filename, error.message)
        raise ApiError(400, error.code, error.message) from None

    sha256 = hashlib.sha256(data).hexdigest()
    existing = models.find_by_sha256(connection, sha256)
    if existing is not None:
        raise ApiError(409, "duplicate", "This file was already uploaded.", {"id": existing.id})

    if writer.player_uuid is not None:
        since = datetime.fromtimestamp(datetime.now(timezone.utc).timestamp() - 86400, timezone.utc).isoformat(timespec="seconds")
        if models.uploads_since(connection, writer.player_uuid, since) >= settings.uploads_per_player_per_day:
            raise ApiError(429, "quota_exceeded", f"At most {settings.uploads_per_player_per_day} uploads per player per day.")
    if models.total_size(connection) + len(data) > settings.max_storage_bytes:
        logger.error("Storage limit of %d bytes reached; refusing upload", settings.max_storage_bytes)
        raise ApiError(507, "storage_full", "The server's storage limit is reached.")

    name = clean_text(display_name, MAX_NAME_LENGTH) if display_name else None
    cosmetic_id = uuid.uuid4().hex
    storage = _storage(request)
    # Store the file first, then register it. The database entry, which is what makes a cosmetic visible and
    # downloadable, is only created once the file is safely on disk; if registering fails, the file is removed.
    stored_filename = storage.save(cosmetic_id, data)
    cosmetic = models.Cosmetic(
        id=cosmetic_id,
        display_name=name or validated.name or original_filename.rsplit(".", 1)[0] or "Untitled cosmetic",
        original_filename=original_filename,
        stored_filename=stored_filename,
        size_bytes=len(data),
        sha256=sha256,
        uploaded_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        validation_status=models.STATUS_APPROVED,
        format_version=validated.format_version,
        model_format=validated.model_format,
        element_count=validated.element_count,
        texture_count=validated.texture_count,
        animation_count=validated.animation_count,
        owner_uuid=writer.player_uuid,
    )
    try:
        with connection:
            models.insert(connection, cosmetic)
    except sqlite3.IntegrityError:
        storage.delete(stored_filename)
        raise ApiError(409, "duplicate", "This file was already uploaded.") from None
    except BaseException:
        storage.delete(stored_filename)
        raise
    logger.info("Stored cosmetic %s (%s, %d bytes)", cosmetic_id, original_filename, len(data))
    return CosmeticResponse.from_model(cosmetic, config.API_PREFIX)


def _find_by_sha256(connection: sqlite3.Connection, sha256: str) -> models.Cosmetic:
    value = sha256.lower()
    cosmetic = models.find_by_sha256(connection, value) if SHA256.match(value) else None
    if cosmetic is None:
        raise ApiError(404, "not_found", "No cosmetic with this SHA-256 exists.")
    return cosmetic


# Registered before "/{cosmetic_id}" routes. The SHA-256 is the asset ID the Orbit mod uses.
@router.get(
    "/by-sha256/{sha256}",
    response_model=CosmeticResponse,
    responses=NOT_FOUND,
    summary="Metadata of the cosmetic with this SHA-256 (the Orbit asset ID)",
)
def get_cosmetic_by_sha256(sha256: str, connection: sqlite3.Connection = Depends(get_connection)) -> CosmeticResponse:
    return CosmeticResponse.from_model(_find_by_sha256(connection, sha256), config.API_PREFIX)


@router.get(
    "/by-sha256/{sha256}/download",
    response_class=FileResponse,
    responses={200: {"content": {"application/json": {}}, "description": "The stored .bbmodel file"}, **NOT_FOUND},
    summary="Download the cosmetic with this SHA-256",
)
def download_cosmetic_by_sha256(request: Request, sha256: str, connection: sqlite3.Connection = Depends(get_connection)) -> FileResponse:
    return _file_response(request, _find_by_sha256(connection, sha256))


@router.get("/{cosmetic_id}", response_model=CosmeticResponse, responses=NOT_FOUND, summary="Metadata of one cosmetic")
def get_cosmetic(cosmetic_id: str, connection: sqlite3.Connection = Depends(get_connection)) -> CosmeticResponse:
    return CosmeticResponse.from_model(_find(connection, cosmetic_id), config.API_PREFIX)


@router.get(
    "/{cosmetic_id}/download",
    response_class=FileResponse,
    responses={
        200: {"content": {"application/json": {}}, "description": "The stored .bbmodel file"},
        **NOT_FOUND,
        409: {"model": ErrorResponse, "description": "The cosmetic is not approved for download"},
    },
    summary="Download an approved cosmetic file",
)
def download_cosmetic(request: Request, cosmetic_id: str, connection: sqlite3.Connection = Depends(get_connection)) -> FileResponse:
    return _file_response(request, _find(connection, cosmetic_id))


def _file_response(request: Request, cosmetic: models.Cosmetic) -> FileResponse:
    if cosmetic.validation_status != models.STATUS_APPROVED:
        raise ApiError(409, "not_approved", "This cosmetic is not approved for download.")
    path = _storage(request).path_for(cosmetic.stored_filename)
    if not path.is_file():
        logger.error("File for cosmetic %s is missing: %s", cosmetic.id, cosmetic.stored_filename)
        raise ApiError(404, "file_missing", "The cosmetic is registered but its file is missing on the server.")
    download_name = cosmetic.original_filename if cosmetic.original_filename.lower().endswith(".bbmodel") else f"{cosmetic.id}.bbmodel"
    return FileResponse(
        path,
        media_type="application/json",
        filename=download_name,
        headers={"X-Content-Type-Options": "nosniff", "X-Orbit-SHA256": cosmetic.sha256},
    )


@router.delete(
    "/{cosmetic_id}",
    response_model=DeleteResponse,
    responses={**NOT_FOUND, 403: {"model": ErrorResponse, "description": "Not in development mode, or not from this computer"}},
    summary="Delete a cosmetic (development only)",
)
def delete_cosmetic(request: Request, cosmetic_id: str, connection: sqlite3.Connection = Depends(get_connection)) -> DeleteResponse:
    require_development(request)
    cosmetic = _find(connection, cosmetic_id)
    # Remove the database entry first so the cosmetic disappears at once; a file left behind by a failure
    # here is cleaned up as an orphan at the next start.
    with connection:
        models.delete(connection, cosmetic.id)
    try:
        _storage(request).delete(cosmetic.stored_filename)
    except OSError:
        logger.exception("Could not delete the file of cosmetic %s; it will be removed at the next start", cosmetic.id)
    logger.info("Deleted cosmetic %s", cosmetic.id)
    return DeleteResponse(id=cosmetic.id, deleted=True)
